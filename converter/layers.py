"""Step 2: build a two-layer scene from one photo + its closeness map.

Foreground layer = the photo itself with its depth. The viewer tears this mesh
wherever depth jumps (see viewer shader), so objects separate from what is
behind them instead of stretching like a rubber sheet.

Background layer = a copy of the photo where every strip *behind* an object
edge has been filled in: depth is extended from the far side, and colour is
generated by an inpainting model. When you lean, that strip is what you see
appear around a person or object - the effect that sells real 3D.

Closeness (inverse depth) is used throughout because on-screen parallax is
proportional to closeness differences, so thresholds mean the same thing
everywhere in the image.
"""
import numpy as np
import cv2


def depth_edges(c, tau):
    """Pixels on the near side of a depth jump larger than tau."""
    k = np.ones((3, 3), np.uint8)
    mx, mn = cv2.dilate(c, k), cv2.erode(c, k)
    jump = (mx - mn) > tau
    near = c > (mx + mn) * 0.5
    return jump & near


def build(rgb, c, inpaint, tau=0.03, max_eye=0.10, strength=0.8, matte=None):
    """Returns dict with background rgb/closeness, the fill mask and stats.

    A pixel needs background behind it if some pixel within distance r is
    farther by more than r / K, where K = pixels of parallax per unit of
    closeness at the largest head offset the viewer allows (max_eye, in window
    widths). That is exactly the condition for being uncovered when you lean,
    so the strip is wide at big depth jumps, thin at small ones, and gently
    sloped surfaces (floors, walls) are never cut.
    """
    h, w = c.shape
    K = max_eye * strength * w            # px of parallax per unit closeness
    rmax = int(np.ceil(K * 1.0)) + 2       # widest possible strip (full-range jump)

    reveal = np.zeros((h, w), bool)
    bg_level = c.copy()
    rw = np.zeros((h, w), np.int32)        # local strip width: smallest radius that triggered
    radii = [r for r in (2, 4, 8, 16, 32, 64, 128, 256) if r <= rmax] or [2]
    for r in sorted(radii, reverse=True):   # small radii last -> most local bg wins
        er = cv2.erode(c, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * r + 1, 2 * r + 1)))
        hit = (c - er) > max(tau, r / K)
        reveal |= hit
        bg_level[hit] = er[hit]
        rw[hit] = r
    reveal = cv2.morphologyEx(reveal.astype(np.uint8), cv2.MORPH_CLOSE, np.ones((5, 5), np.uint8)) > 0
    B = rmax

    # The fill must only "see" background. Mark as unknown every pixel that is
    # in front of the background around it (radius ~1.5x the widest strip),
    # so the inpainter treats near objects like objects to erase. Only the
    # strip next to the background side is used, which is where the fill is
    # most reliable. Thick objects keep their far interior as context, but
    # that is >= 1.5 strips away from anything we use.
    # Grow the hole inward only: pixels within g of a strip that are nearer
    # than the background value behind that strip (plus tau). Floors and
    # shelves around the object stay as context.
    # Grow each strip inward by an amount set by its depth gap: behind a
    # person's outline (big gap) the whole nearby subject is treated as
    # "to erase", so the fill only copies true background; behind a collar
    # (small gap) it stays local, so the fill continues the same fabric.
    gapK = (c - bg_level) * K               # px the strip can open at max lean
    inward = np.zeros((h, w), bool)
    for r in radii:
        lo_px, hi_px = (r * 0.7, r * 1.4)
        m = reveal & (gapK * 0.6 >= lo_px) & (gapK * 0.6 < hi_px)
        if r == radii[0]:
            m |= reveal & (gapK * 0.6 < lo_px)
        if r == radii[-1]:
            m |= reveal & (gapK * 0.6 >= hi_px)
        if not m.any():
            continue
        dk = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * r + 1,) * 2)
        Fr = np.where(m, bg_level, 1.0).astype(np.float32)
        Fn = cv2.erode(Fr, dk)
        inward |= (cv2.dilate(m.astype(np.uint8), dk) > 0) & (c > Fn + max(tau, 0.06))
    hole = reveal | inward
    base = rgb
    if matte is not None:
        # Edge band from matting: the background side keeps its real colour
        # (with any foreground blend removed); the subject side is unknown
        # background, so it joins the area to fill.
        band, a = matte["band"], matte["alpha"]
        base = np.where(band[..., None], matte["B"], rgb)
        hole |= band & (a >= 0.5)
    hole = cv2.dilate(hole.astype(np.uint8), np.ones((5, 5), np.uint8)) > 0

    # --- background depth: a smooth "objects pushed back" surface.
    # Anything narrower than ~2 strips (poles, spokes, a rocket) is removed
    # entirely; big objects keep their depth but with a ramp instead of a
    # step at the edge. Being smooth, this layer never needs cutting, so it
    # can always be shown wherever the foreground opens up - no black holes.
    se = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * rmax + 1, 2 * rmax + 1))
    far = cv2.GaussianBlur(cv2.erode(c, se), (0, 0), max(2.0, rmax / 2))
    c_bg = np.minimum(c, far)
    c_bg[reveal] = np.minimum(c_bg[reveal], bg_level[reveal])
    c_bg = cv2.GaussianBlur(c_bg, (0, 0), 2.0)
    if matte is not None:
        # across the matting band the background layer IS the far surface
        # (it shows through the soft edge), so give it that surface's depth
        bandf = cv2.GaussianBlur(matte["band"].astype(np.float32), (0, 0), 1.5)
        c_bg = c_bg * (1 - bandf) + matte["c_bgband"] * bandf

    # --- background colour: generative fill
    filled = inpaint(base, hole)
    # feathered seam straddling the hole boundary (the fill is valid a few px
    # outside the hole), so no hard line traces the subject
    hu = hole.astype(np.uint8)
    signed = cv2.distanceTransform(hu, cv2.DIST_L2, 3) - cv2.distanceTransform(1 - hu, cv2.DIST_L2, 3)
    wgt = np.clip((signed + 2.0) / 4.0, 0, 1)[..., None]
    rgb_bg = (base * (1 - wgt) + filled * wgt + 0.5).astype(np.uint8)

    return {
        "rgb_bg": rgb_bg,
        "c_bg": c_bg.astype(np.float32),
        "reveal": reveal,
        "hole": hole,
        "edge": depth_edges(c, tau),
        "band_px": B,
        "reveal_pct": float(reveal.mean() * 100),
    }


def _smooth_inside(img, mask, sigma):
    """Blur only inside mask (normalised convolution) so the filled background
    depth is smooth but the untouched pixels keep their exact values."""
    if sigma < 0.5 or not mask.any():
        return img
    m = mask.astype(np.float32)
    keep = 1 - m
    num = cv2.GaussianBlur(img * 1.0, (0, 0), sigma)
    out = img.copy()
    out[mask] = num[mask]
    return out


def grade(c, strength=0.8, subject=None):
    """3D-movie style depth grading.

    Puts the subject at the window plane (zero parallax), lets nearer things
    come slightly out toward the viewer, and pushes the background back.
    Returns per-pixel depth in *window units* (window plane = 1.0) and the
    parameters, so the viewer can reproduce or live-adjust them.

    strength : total relative parallax budget P = D0 * (1/z_near - 1/z_far)
    """
    if subject is None:
        subject = subject_closeness(c)
    P = float(np.clip(strength, 0.1, 0.95))
    s = float(np.clip(subject, 0.05, 0.98))
    if s * P > 0.9:          # keep the far plane at a finite distance
        P = 0.9 / s
    inv_far = 1.0 - s * P     # 1/z_far in window units
    inv_z = inv_far + c * P
    return (1.0 / inv_z).astype(np.float32), {"P": P, "subject": s,
                                             "z_near": 1 / (inv_far + P), "z_far": 1 / inv_far}


def subject_closeness(c):
    """Closeness of the probable subject.

    Prefers pixels that stand out in front of their surroundings (a person in
    a doorway, a pet on a sofa) and sit near the centre, rather than whatever
    is simply nearest (floors, door frames at the image edge)."""
    h, w = c.shape
    s = 256 / max(h, w)
    cs = cv2.resize(c, (max(8, int(w * s)), max(8, int(h * s))), interpolation=cv2.INTER_AREA)
    hh, ww = cs.shape
    yy, xx = np.mgrid[0:hh, 0:ww]
    centre = np.exp(-(((xx - ww / 2) / (0.3 * ww)) ** 2 + ((yy - hh * 0.45) / (0.33 * hh)) ** 2))
    pop = cs - cv2.GaussianBlur(cs, (0, 0), max(hh, ww) / 6)     # stands out from local scene
    wgt = centre * np.clip(pop, 0, None)
    if wgt.sum() < 1e-3 * wgt.size:                               # nothing stands out: centre fallback
        wgt = centre
    # weighted histogram peak = the depth most of the standout, central stuff sits at
    hist, edges = np.histogram(cs.ravel(), bins=64, range=(0, 1), weights=wgt.ravel())
    hist = np.convolve(hist, np.ones(5) / 5, mode="same")
    k = int(np.argmax(hist))
    return float(0.5 * (edges[k] + edges[k + 1]))
